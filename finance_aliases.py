# 代码正则：6 位纯数字（证券代码形态，避免误匹配日期/金额）
_CODE_RE = re.compile(r"\b\d{6}\b")


def expand_entities(full_text: str) -> list[str]:
    """实体别名扩展：命中简称追加全称，命中 6 位代码追加公司名"""
    extras = []
    for alias, full in STOCK_ALIASES.items():
        if alias in full_text:
            extras.append(full)
    for code, full in STOCK_CODES.items():
        if code in full_text:
            extras.append(full)
    return extras


def expand_metrics(full_text: str) -> list[str]:
    """指标同义词扩展：命中触发词追加全部变体（含变体的分词由检索层处理）"""
    extras = []
    for trigger, syns in METRIC_SYNONYMS.items():
        if trigger in full_text:
            extras.extend(syns)
    return extras


def expand_all(full_text: str) -> list[str]:
    """统一入口：实体 + 指标扩展（去重，控制数量防止查询过度膨胀）"""
    extras = expand_entities(full_text) + expand_metrics(full_text)
    seen, out = set(), []
    for e in extras:
        if e and e not in seen:
            seen.add(e)
            out.append(e)
    return out[:15]
